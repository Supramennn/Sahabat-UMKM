import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname } from 'node:path'
import type { Database } from './client.ts'

/**
 * Cadangan logis untuk database PostgreSQL Sahabat-UMKM.
 *
 * Mengapa dibuat sendiri padahal PostgreSQL punya pg_dump: distribusi PostgreSQL
 * tertanam yang dipakai pengembangan (@embedded-postgres untuk klaster .pgdata)
 * hanya mengirim initdb, pg_ctl, dan postgres. Mesin tanpa atau dengan Docker
 * pun tak selalu punya binari pg_dump yang cocok dengan versi servernya, dan di
 * hosting produksi binari itu juga tidak dijamin ada. Membaca data sebagai SQL
 * dari klien aplikasi memberi satu jalur yang sama di mesin lokal, di klaster
 * tertanam, dan di hosting produksi.
 *
 * Yang dicadangkan hanya isi schema public. schema_migrations sengaja tidak
 * ikut: pemulihan selalu menjalankan seluruh migrasi lebih dulu (migrate di
 * src/migrate.ts), lalu memuat data di atasnya. Nilai kolom dirender sisi
 * server (format('%L::%s', kolom::text, format_type(...))) supaya tidak ada
 * presisi yang hilang di klien; timestamptz dirender lewat `at time zone 'UTC'`
 * plus akhiran +00 supaya berkasnya benar di server tujuan dengan zona bawaan
 * yang berbeda.
 *
 * Pemulihan menonaktifkan trigger milik pengguna (disable trigger user) dan
 * mengosongkan tabel (truncate) sebelum memuat supaya hasil pemulihan persis
 * sama dengan sumber. Tanpa itu, trigger seperti set_default_location pada
 * locations akan menulis ulang workspaces ketika baris dihasilkan ulang, dan
 * hasilnya bisa berbeda dari data sumber. Dua jenis pernyataan itu butuh hak
 * pemilik tabel: akun klaster tertanam adalah pemiliknya, peran aplikasi
 * produksi biasanya bukan, jadi itu tercatat sebagai batas di dokumen rilis.
 *
 * Urutan pemuatan: tabel diurutkan topologis dari graf FK supaya kunci asing
 * tetap dihormati tanpa menunda batasan; kolom identity dimasukkan dengan
 * overriding system value, lalu sekuensnya selaras lewat setval ke maksimum
 * + 1; sekuens mandiri seperti payment_numbers di-setval ke nilai terakhirnya
 * saat cadangan dibuat.
 *
 * Ujinya ada di packages/db/test-postgres/cadangan-restore.test.ts: database
 * hasil pemulihan dicadangkan lagi memakai kode yang sama, dan hasilnya harus
 * identik per pernyataan. Perbedaan sekecil apa pun terlihat sebagai indeks
 * pernyataan yang berbeda.
 */

/** Baris per pernyataan INSERT supaya satu pernyataan tidak membengkak. */
const HALAMAN_BARIS = 500

const KATA_MULAI = 'begin;'
const KATA_SELESAI = 'commit;'

export interface RincianTabel {
  nama: string
  baris: number
}

export interface WaktuCadangan {
  /** Waktu membaca katalog (tabel, kolom, kunci, jumlah baris). */
  katalog: number
  /** Waktu membaca isi tabel dan menyusun pernyataan. */
  data: number
  total: number
}

export interface CadanganTerbuat {
  pernyataan: string[]
  barisPerTabel: RincianTabel[]
  waktu: WaktuCadangan
}

export interface WaktuPulihkan {
  total: number
}

export interface HasilVerifikasi {
  sama: boolean
  /** Sampel perbedaan pertama, untuk pesan galat. */
  selisih: string[] | null
  tabel: { nama: string; sumber: number; pulih: number }[]
  waktu: { total: number }
}

export interface CadanganBerkas {
  dibuat: string | null
  sumber: string | null
  pernyataan: string[]
}

interface KolomKatalog {
  nomor: number
  nama: string
  tipe: string
  /** Kapanpun identitas (generated always atau generated by default). */
  identitas: boolean
  /** Hanya generated always, yang mengharuskan overriding system value. */
  selalu: boolean
}

interface PetaTabel {
  nama: string
  kolom: KolomKatalog[]
  /** Kolom penyusun urutan baris: kunci primer, atau seluruh kolom. */
  urutan: string[]
  baris: number
}

function kutipNama(nama: string): string {
  return `"${nama.replaceAll('"', '""')}"`
}

function kutipLiteral(nilai: string): string {
  return `'${nilai.replaceAll("'", "''")}'`
}

function alamatTabel(nama: string): string {
  return `public.${kutipNama(nama)}`
}

function miliSejak(tanda: bigint): number {
  return Number(process.hrtime.bigint() - tanda) / 1_000_000
}

/**
 * Kahn topological sort. Deterministik: tabel dan tepian diproses dengan
 * urutan nama supaya hasil pembangkitan cadangan tetap sama antar sesi.
 */
function urutkanTopologi(namaTabel: string[], tepiMentah: { anak: string; induk: string }[]): string[] {
  // Tepian diurutkan dulu: kueri katalog membiarkan urutannya berubah antar
  // sesi, dan Kahn yang menumpuk anak lewat urutan tepi akan melenceng dari
  // itu. Tanpa ini, cadangan dua kalinya bisa menghasilkan berkas berbeda.
  const tepi = [...tepiMentah].sort(
    (a, b) => a.induk.localeCompare(b.induk) || a.anak.localeCompare(b.anak),
  )
  const masuk = new Map<string, number>()
  const anakDari = new Map<string, string[]>()
  for (const t of [...namaTabel].sort()) {
    masuk.set(t, 0)
    anakDari.set(t, [])
  }
  for (const e of tepi) {
    if (!masuk.has(e.anak) || !masuk.has(e.induk)) continue
    masuk.set(e.anak, (masuk.get(e.anak) ?? 0) + 1)
    anakDari.get(e.induk)!.push(e.anak)
  }

  const antre = [...masuk.entries()].filter(([, v]) => v === 0).map(([k]) => k)
  const hasil: string[] = []
  while (antre.length > 0) {
    const t = antre.shift()!
    hasil.push(t)
    for (const anak of anakDari.get(t)!) {
      const sisa = (masuk.get(anak) ?? 0) - 1
      masuk.set(anak, sisa)
      if (sisa === 0) antre.push(anak)
    }
  }

  if (hasil.length !== masuk.size) {
    const tersiklis = [...masuk.entries()].filter(([, v]) => v > 0).map(([k]) => k)
    throw new Error(
      `Tabel berikut membentuk siklus FK sehingga tidak bisa diurutkan untuk pemulihan: ${tersiklis.join(', ')}`,
    )
  }
  return hasil
}

function ekspresiNilai(alias: string, kolom: KolomKatalog): string {
  const rujuk = `${alias}.${kutipNama(kolom.nama)}`
  if (kolom.tipe.includes('with time zone')) {
    // Nilai dirender sebagai naif UTC dan diberi akhiran +00, lalu dikembalikan
    // sebagai timestamptz. Hasilnya sama persis di server tujuan berapapun zona
    // bawaannya; cast teks biasa akan mengikuti zona sesi dan melenceng.
    return `coalesce(format('%L::%s', (${rujuk} at time zone 'UTC')::text || '+00', ${kutipLiteral(kolom.tipe)}), 'null')`
  }
  return `coalesce(format('%L::%s', ${rujuk}::text, ${kutipLiteral(kolom.tipe)}), 'null')`
}

export async function buatCadangan(db: Database): Promise<CadanganTerbuat> {
  const mulai = process.hrtime.bigint()

  const tabelRows = await db.query<{ nama: string }>(
    `select c.relname::text as nama
     from pg_class c
     join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public' and c.relkind = 'r' and c.relname <> 'schema_migrations'`,
  )
  const tepiRows = await db.query<{ anak: string; induk: string }>(
    `select anak.relname::text as anak, induk.relname::text as induk
     from pg_constraint k
     join pg_class anak on anak.oid = k.conrelid
     join pg_class induk on induk.oid = k.confrelid
     where k.contype = 'f'
       and anak.relkind = 'r'
       and induk.relkind = 'r'`,
  )

  const urutTabel = urutkanTopologi(
    tabelRows.rows.map((r) => r.nama),
    tepiRows.rows,
  )

  const peta: PetaTabel[] = []
  for (const nama of urutTabel) {
    const kolomRows = await db.query<{ nomor: number; nama: string; tipe: string; identitas: boolean; selalu: boolean }>(
      `select a.attnum as nomor, a.attname::text as nama,
              format_type(a.atttypid, a.atttypmod)::text as tipe,
              (a.attidentity <> '') as identitas,
              (a.attidentity = 'a') as selalu
       from pg_attribute a
       where a.attrelid = to_regclass($1) and a.attnum > 0 and not a.attisdropped
       order by a.attnum`,
      [alamatTabel(nama)],
    )
    const kolom = kolomRows.rows

    const pk = await db.query<{ indkey: string | null }>(
      `select i.indkey::text as indkey
       from pg_index i
       where i.indrelid = to_regclass($1) and i.indisprimary`,
      [alamatTabel(nama)],
    )
    const namaPerNomor = new Map(kolom.map((k) => [k.nomor, k.nama]))
    const urutanPk = (pk.rows[0]?.indkey ?? '')
      .split(/\s+/)
      .filter(Boolean)
      .map(Number)
      .map((nomor) => namaPerNomor.get(nomor))
      .filter((n): n is string => n !== undefined)

    const barisRows = await db.query<{ baris: string }>(
      `select count(*)::text as baris from ${alamatTabel(nama)}`,
    )

    peta.push({
      nama,
      kolom,
      urutan: urutanPk.length > 0 ? urutanPk : kolom.map((k) => k.nama),
      baris: Number(barisRows.rows[0]?.baris ?? 0),
    })
  }

  const waktuKatalog = miliSejak(mulai)
  const mulaiData = process.hrtime.bigint()

  const pernyataan: string[] = []
  pernyataan.push(...urutTabel.map((n) => `alter table ${alamatTabel(n)} disable trigger user;`))
  pernyataan.push(
    `truncate table ${urutTabel.map(alamatTabel).join(', ')} restart identity cascade;`,
  )

  for (const t of peta) {
    if (t.baris > 0) {
      const kepala = `insert into ${alamatTabel(t.nama)} (${t.kolom
        .map((k) => kutipNama(k.nama))
        .join(', ')})${t.kolom.some((k) => k.selalu) ? ' overriding system value' : ''} values `

      const nilaiKolom = t.kolom.map((k) => ekspresiNilai('t', k))
      const gabungBaris = nilaiKolom.map((_, i) => `s.e${i}`).join(` || ', ' || `)
      const gabungUrut = t.urutan.map((n) => `t.${kutipNama(n)}`).join(', ')

      const sqlHalaman = (dari: number, sampai: number) =>
        `select ${kutipLiteral(kepala)} || string_agg(
          '(' || ${gabungBaris} || ')',
          ', ' || chr(10) order by nomor
        ) || ';' as bagian
        from (
          select row_number() over (order by ${gabungUrut}) as nomor,
                 ${nilaiKolom.map((e, i) => `(${e}) as e${i}`).join(', ')}
          from ${alamatTabel(t.nama)} t
        ) s
        where s.nomor between ${dari} and ${sampai}`

      for (let mulaiHalaman = 1; ; mulaiHalaman += HALAMAN_BARIS) {
        const halaman = await db.query<{ bagian: string | null }>(
          sqlHalaman(mulaiHalaman, mulaiHalaman + HALAMAN_BARIS - 1),
        )
        const bagian = halaman.rows[0]?.bagian
        if (!bagian) break
        pernyataan.push(bagian)
      }
    }

    // Baris identity dimasukkan dengan override, jadi sekuensnya selaras ulang
    // lewat setval — juga untuk tabel yang kini kosong: barisnya bisa sudah
    // dihapus padahal sekuensnya sudah maju.
    for (const k of t.kolom.filter((k) => k.identitas)) {
      pernyataan.push(
        `select setval(pg_get_serial_sequence(${kutipLiteral(alamatTabel(t.nama))}, ${kutipLiteral(k.nama)}), (select coalesce(max(${kutipNama(k.nama)}), 0) from ${alamatTabel(t.nama)}) + 1, false);`,
      )
    }
  }

  // Sekuens mandiri tidak dimiliki kolom mana pun, jadi dia harus ikut
  // secara eksplisit. Kolom identity diatur ulang lewat blok setval di atas.
  const seqRows = await db.query<{ nama: string }>(
    `select c.relname::text as nama
     from pg_class c
     join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public' and c.relkind = 'S'
       and not exists (
         select 1 from pg_depend d
         where d.objid = c.oid and d.deptype in ('a', 'i')
       )
     order by c.relname`,
  )
  for (const s of seqRows.rows) {
    const nilai = await db.query<{ last_value: string; is_called: boolean }>(
      `select last_value, is_called from ${alamatTabel(s.nama)}`,
    )
    const baris = nilai.rows[0]
    if (!baris) continue
    pernyataan.push(
      `select setval(${kutipLiteral(alamatTabel(s.nama))}, ${baris.last_value}, ${baris.is_called});`,
    )
  }

  pernyataan.push(...urutTabel.map((n) => `alter table ${alamatTabel(n)} enable trigger user;`))

  return {
    pernyataan,
    barisPerTabel: peta.map((p) => ({ nama: p.nama, baris: p.baris })),
    waktu: {
      katalog: waktuKatalog,
      data: miliSejak(mulaiData),
      total: miliSejak(mulai),
    },
  }
}

export async function pulihkanCadangan(
  target: Database,
  pernyataan: readonly string[],
): Promise<WaktuPulihkan> {
  const mulai = process.hrtime.bigint()
  await target.transaction(async (tx) => {
    for (const s of pernyataan) {
      await tx.exec(s)
    }
  })
  return { total: miliSejak(mulai) }
}

/**
 * Bukti pemulihan: database hasil pemulihan dicadangkan lagi dengan kode yang
 * sama, lalu kedua daftar pernyataan dibandingkan. Identik berarti seluruh
 * kolom dirender sama oleh server — presisi, NULL, yang paling mudah salah
 * pun tak luput. Selain itu, jumlah baris per tabel dibandingkan sebagai
 * ringkasan yang mudah dibaca manusia.
 */
export async function verifikasiPulihan(
  sumber: Database,
  pulih: Database,
  cadangan: CadanganTerbuat,
): Promise<HasilVerifikasi> {
  const mulai = process.hrtime.bigint()
  const ulang = await buatCadangan(pulih)

  const selisih: string[] = []
  const panjang = Math.max(cadangan.pernyataan.length, ulang.pernyataan.length)
  for (let i = 0; i < panjang && selisih.length < 3; i++) {
    const dariSumber = cadangan.pernyataan[i] ?? '(tidak ada)'
    const dariPulih = ulang.pernyataan[i] ?? '(tidak ada)'
    if (dariSumber !== dariPulih) {
      selisih.push(
        `pernyataan ${i + 1}:\n  sumber: ${dariSumber.slice(0, 240)}\n  pulih : ${dariPulih.slice(0, 240)}`,
      )
    }
  }

  const tabel = ulang.barisPerTabel.map((b) => ({
    nama: b.nama,
    sumber: cadangan.barisPerTabel.find((c) => c.nama === b.nama)?.baris ?? -1,
    pulih: b.baris,
  }))

  return {
    sama: selisih.length === 0,
    selisih: selisih.length > 0 ? selisih : null,
    tabel,
    waktu: { total: miliSejak(mulai) },
  }
}

export async function simpanCadangan(
  berkas: string,
  cadangan: CadanganTerbuat,
  sumber: string,
): Promise<void> {
  await mkdir(dirname(berkas), { recursive: true })
  const isi = [
    '-- Cadangan Sahabat-UMKM v1',
    `-- Sumber : ${sumber}`,
    `-- Dibuat : ${new Date().toISOString()}`,
    '-- Isi    : seluruh tabel schema public sebagai pernyataan SQL, terbungkus',
    '--           begin/commit. Menjalankan berkas ini dengan psql -1 -f atau',
    '--           lewat pulihkanCadangan() menghasilkan isi database yang identik.',
    KATA_MULAI,
    ...cadangan.pernyataan,
    KATA_SELESAI,
    '',
  ].join('\n')
  await writeFile(berkas, isi, 'utf8')
}

export async function muatCadanganDariBerkas(berkas: string): Promise<CadanganBerkas> {
  const teks = await readFile(berkas, 'utf8')
  const ambilKepala = (ibu: RegExp): string | null =>
    teks.match(ibu)?.[1]?.trim() ?? null

  const pernyataan = pecahPernyataan(teks)
  if (pernyataan[0] === KATA_MULAI) pernyataan.shift()
  if (pernyataan[pernyataan.length - 1] === KATA_SELESAI) pernyataan.pop()

  return {
    dibuat: ambilKepala(/^-- Dibuat : (.*)$/m),
    sumber: ambilKepala(/^-- Sumber : (.*)$/m),
    pernyataan,
  }
}

/**
 * Pemecah pernyataan SQL yang peka terhadap string kutip satu dan komentar.
 * Nilai berisi `;`, baris baru, atau `--` tetap utuh karena dipecah hanya di
 * `;` di luar tanda kutip.
 */
function pecahPernyataan(teks: string): string[] {
  const hasil: string[] = []
  let bagian = ''
  let dalamKutip = false

  for (let i = 0; i < teks.length; i++) {
    const c = teks[i]!
    if (dalamKutip) {
      bagian += c
      if (c === "'") {
        if (teks[i + 1] === "'") {
          bagian += "'"
          i++
        } else {
          dalamKutip = false
        }
      }
      continue
    }
    if (c === "'") {
      dalamKutip = true
      bagian += c
      continue
    }
    if (c === '-' && teks[i + 1] === '-') {
      while (i < teks.length && teks[i] !== '\n') i++
      continue
    }
    if (c === ';') {
      const tersusun = bagian.trim()
      if (tersusun) hasil.push(`${tersusun};`)
      bagian = ''
      continue
    }
    bagian += c
  }

  const sisa = bagian.trim()
  if (sisa) hasil.push(`${sisa};`)
  return hasil
}
